"""PLAN.md 5번 변경 이력의 시각을 git 커밋 시각으로 교정한다.

왜: 이력에 적힌 시각(10-13 10:30~23:30)이 실제 작업 시각과 맞지 않았다.
근거:
  - 10-13 09:04에 뜬 백업(`..._backup_1013_am`) 안의 PLAN.md가 **10-12 16:35**자다
    → 10-12 저녁에는 작업이 없었고, 아래 작업들은 전부 10-13 09:04 이후다.
  - 10-13 16:00 백업 안의 돌봄밀도.html이 **15:38**자다 → 그날 작업은 15:42에 끝났다.
  - 그 사이 git 커밋 24건의 시각이 남아 있다. 그 값을 쓴다.

선번호로 바꾸면 파일이 밀렸을 때 엉뚱한 줄을 덮어쓴다(실제로 한 번 그랬다).
그래서 **행의 고유 문구를 앵커로** 잡고, 치환이 정확히 1건인지 검사한다.

실행: python tools/fix_log_times.py PLAN.md
"""
import sys, io

path = sys.argv[1] if len(sys.argv) > 1 else "PLAN.md"

# (앵커로 쓸 현재 문구, 바꿀 문구) — 앵커는 '| 시각 | 그 행의 첫 문구'까지
PAIRS = [
    # 이번 세션 작업분 — 커밋 시각으로
    ("| **10-13 21:00** | **자가 점검 89점",  "| **10-13 22:31** | **자가 점검 89점"),
    ("| **10-13 16:30** | **데이터 1종 → 2종.**", "| **10-13 20:06** | **데이터 1종 → 2종.**"),
    # 10-13 오전·오후 작업분 — git 커밋 시각으로
    ("| **10-13 23:30** | **카드 행동 줄 개편**", "| **10-13 15:38** | **카드 행동 줄 개편**"),
    ("| 10-13 22:40 | **표지 히어로 애니메이션 교체**", "| 10-13 15:21 | **표지 히어로 애니메이션 교체**"),
    ("| 10-13 22:10 | **비용 보기 기능 추가**", "| 10-13 15:16 | **비용 보기 기능 추가**"),
    ("| 10-13 21:30 | **카드 내부 행까지 정렬**", "| 10-13 15:02 | **카드 내부 행까지 정렬**"),
    ("| 10-13 21:00 | **카드 버튼 높이 정렬**", "| 10-13 14:58 | **카드 버튼 높이 정렬**"),
    ("| 10-13 20:20 | **\"내 동네 먼저\" 정렬 추가**", "| 10-13 14:50 | **\"내 동네 먼저\" 정렬 추가**"),
    ("| 10-13 19:40 | **Claude Design 1차 시안 반영**", "| 10-13 14:43 | **Claude Design 1차 시안 반영**"),
    ("| 10-13 19:00 | 화면·발표 용어", "| 10-13 14:29 | 화면·발표 용어"),
    ("| 10-13 18:40 | **발표자료 가독성 보강**", "| 10-13 14:22 | **발표자료 가독성 보강**"),
    ("| 10-13 18:00 | **발표자료 애니메이션 확대**", "| 10-13 14:17 | **발표자료 애니메이션 확대**"),
    ("| 10-13 17:20 | **현대적 디테일 보강**", "| 10-13 14:06 | **현대적 디테일 보강**"),
    ("| 10-13 16:10 | **발표자료를 서비스와 같은 시각 문법으로 개정**", "| 10-13 11:38 | **발표자료를 서비스와 같은 시각 문법으로 개정**"),
    ("| 10-13 15:40 | **시각 문법을 토스·당근 계열로 개정**", "| 10-13 11:29 | **시각 문법을 토스·당근 계열로 개정**"),
    ("| 10-13 15:10 | **가독성 보강**", "| 10-13 11:21 | **가독성 보강**"),
    ("| 10-13 14:30 | **디자인 시스템 수립·적용**", "| 10-13 11:15 | **디자인 시스템 수립·적용**"),
    ("| 10-13 13:00 | `CLAUDE.md`를 강의 부록", "| 10-13 09:33 | `CLAUDE.md`를 강의 부록"),
    ("| 10-13 11:30 | 디자인 정돈 4가지", "| 10-13 ~09:30 | 디자인 정돈 4가지"),
    ("| 10-13 10:30 | 기능 3개 추가", "| 10-13 ~09:20 | 기능 3개 추가"),
]

text = io.open(path, encoding="utf-8").read()
before = text
errors = []
for old, new in PAIRS:
    n = text.count(old)
    if n != 1:
        errors.append(f"  앵커 {n}건 (1건이어야 함): {old[:46]}")
        continue
    text = text.replace(old, new, 1)

if errors:
    print("### 중단 — 앵커가 유일하지 않다. 파일을 건드리지 않았다.")
    print("\n".join(errors))
    sys.exit(1)

io.open(path, "w", encoding="utf-8", newline="").write(text)
print(f"{len(PAIRS)}개 행 교정 · {len(before)} → {len(text)} chars")
